"""modular_path.py — the tutorial path, sculpted from the modular class system.

Palle, 23 Oct: "the reason for this is also to sculpt out the tutorial path". The
terms of commons/modular/terms.json derive from one another (`from`); a topological
order of that derivation IS a lesson order: every term is built from things the
learner has already met. This writes doc/book/course/MODULAR_PATH.md — one lesson
per term, in derivation order inside each chapter: the expression, what it is made
of, what it becomes, which registry artifacts the scanner reads as that term
(commons/data/modular_signatures.json), and the spine maps those artifacts stand in
(commons/data/void_spawnlists.json) — so the path points at rooms that already exist.

  python tools/modular_path.py            # write the markdown
  python tools/modular_path.py --json     # the same as JSON on stdout
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TERMS = ROOT / "commons" / "modular" / "terms.json"
SIGS = ROOT / "commons" / "data" / "modular_signatures.json"
SPAWN = ROOT / "commons" / "data" / "void_spawnlists.json"
OUT = ROOT / "doc" / "book" / "course" / "MODULAR_PATH.md"


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def order(terms: dict) -> list[str]:
    """Topological order by `from`, stable within the file's own order."""
    done: list[str] = []
    seen: set[str] = set()

    def visit(t: str, stack: tuple = ()):
        if t in seen or t not in terms:
            return
        if t in stack:
            raise SystemExit(f"cycle through {t}: {' -> '.join(stack + (t,))}")
        for p in terms[t].get("from", []):
            visit(p, stack + (t,))
        seen.add(t)
        done.append(t)

    for t in terms:
        visit(t)
    return done


def build() -> dict:
    doc = load(TERMS)
    terms = doc["terms"]
    chapters = doc.get("chapters", [])
    sigs = load(SIGS).get("signatures", {})
    items = load(SPAWN).get("items", {})
    seq_order = order(terms)
    children = {t: [c for c in terms if t in terms[c].get("from", [])] for t in terms}
    by_term: dict[str, list[str]] = {}
    for tok, s in sigs.items():
        if s.get("term"):
            by_term.setdefault(s["term"], []).append(tok)
    lessons = []
    for i, t in enumerate(seq_order):
        rec = terms[t]
        arts = sorted(by_term.get(t, []))
        maps: dict[str, int] = {}
        for tok in arts:
            for m in items.get(tok, {}).get("maps", []):
                maps[m] = maps.get(m, 0) + 1
        depth = 0
        if rec.get("from"):
            depth = 1 + max(lessons[seq_order.index(p)]["depth"] for p in rec["from"] if p in seq_order[:i])
        lessons.append({"n": i + 1, "term": t, "label": rec.get("label", t), "chapter": rec.get("chapter", ""), "expr": rec.get("expr", ""),
                        "from": sorted(set(rec.get("from", []))), "becomes": children[t], "depth": depth,
                        "artifacts": arts[:12], "artifact_count": len(arts),
                        "maps": sorted(maps, key=lambda m: -maps[m])[:8], "map_count": len(maps), "token": f"mod_{t}"})
    return {"chapters": chapters, "lessons": lessons}


def markdown(path: dict) -> str:
    lines = ["# The modular path — the tutorial sculpted from the class system", "",
             "*Generated by `tools/modular_path.py` from `commons/modular/terms.json` (the terms), "
             "`commons/data/modular_signatures.json` (what the scanner reads each registry artifact as — a hypothesis) and "
             "`commons/data/void_spawnlists.json` (where those artifacts stand). Do not edit; edit the terms.*", "",
             "Every lesson is one term, built from terms the learner has already met: the order is the derivation order "
             "of the grammar, chapter by chapter. Each term is also a registry token, `mod_<term>`, spawnable from the "
             "wrist menu and placeable in rooms.json or a map, so a lesson can be stood in before it is read.", ""]
    by_ch: dict[str, list[dict]] = {}
    for l in path["lessons"]:
        by_ch.setdefault(l["chapter"], []).append(l)
    for ch in path["chapters"]:
        if ch not in by_ch:
            continue
        lines.append(f"## {ch}")
        lines.append("")
        for l in by_ch[ch]:
            lines.append(f"### {l['n']}. {l['label']}  `{l['token']}`")
            lines.append("")
            lines.append(f"`{l['expr']}`")
            lines.append("")
            if l["from"]:
                lines.append(f"- **made of:** {', '.join(l['from'])}")
            if l["becomes"]:
                lines.append(f"- **becomes:** {', '.join(l['becomes'])}")
            if l["artifact_count"]:
                more = f" … (+{l['artifact_count'] - len(l['artifacts'])})" if l["artifact_count"] > len(l["artifacts"]) else ""
                lines.append(f"- **the registry reads as this ({l['artifact_count']}):** {', '.join(l['artifacts'])}{more}")
            if l["map_count"]:
                lines.append(f"- **stands in ({l['map_count']} maps):** {', '.join(l['maps'])}")
            lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    path = build()
    if a.json:
        print(json.dumps(path, indent=1))
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(markdown(path), encoding="utf-8")
    n = len(path["lessons"])
    with_rooms = sum(1 for l in path["lessons"] if l["map_count"])
    print(f"wrote {OUT.relative_to(ROOT)}: {n} lessons in {len(path['chapters'])} chapters, {with_rooms} with rooms to stand in")
    return 0


if __name__ == "__main__":
    sys.exit(main())
