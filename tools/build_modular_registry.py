"""build_modular_registry.py — every term of the modular class system as a registry token.

commons/modular/terms.json is the one source; this writes
commons/artifacts/registry/modular.json with a token `mod_<term>` per term, all on the
one scene commons/modular/composite.tscn, carrying `default_params: {term}` so the
Void's builder (registry default_params → config_term meta → apply_grid_config) and the
grid's token parser both build the right thing. The validator's catalog reads every
registry file, so the tokens are placeable in rooms.json and in map_data.json at once.

  python tools/build_modular_registry.py            # write
  python tools/build_modular_registry.py --check    # exit 1 if the file is stale
"""
from __future__ import annotations

import argparse
import json
import sys
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TERMS = ROOT / "commons" / "modular" / "terms.json"
OUT = ROOT / "commons" / "artifacts" / "registry" / "modular.json"
SCENE = "res://commons/modular/composite.tscn"

FOOTPRINT = {  # cells, by chapter: most things fit a cell; assemblages and arrays take two
    "point": [1, 1, 1], "line": [2, 1, 1], "association": [2, 1, 1], "triangle": [2, 1, 2], "solid": [1, 1, 1],
    "assemblage": [2, 1, 2], "transformation": [2, 1, 2], "array": [2, 1, 2], "logic": [2, 1, 2], "motion": [2, 1, 2],
}


def build() -> dict:
    doc = json.loads(TERMS.read_text(encoding="utf-8"))
    terms = doc["terms"]
    artifacts = {}
    for tid, t in terms.items():
        token = f"mod_{tid}"
        chapter = t.get("chapter", "")
        editable_recipe = t.get("editor_adapter") == "recipe_area"
        artifacts[token] = {
            "lookup_name": token,
            "name": f"modular · {t.get('label', tid)}",
            "description": f"{t.get('label', tid)} = {t.get('expr', '')}. A term of the modular class system (commons/modular/terms.json), built from its parents at ready.",
            "category": "modular",
            "complexity": "beginner",
            "scene": "res://commons/modular/recipe_area.tscn" if editable_recipe else SCENE,
            "default_params": {"recipe": tid} if editable_recipe else {"term": tid},
            "configure_before_ready": True,
            "map_ready": True,
            "include_in_map_data": True,
            "footprint": FOOTPRINT.get(chapter, [1, 1, 1]),
            "size_group": "compact" if FOOTPRINT.get(chapter, [1])[0] == 1 else "medium",
            "tags": ["modular", chapter] + (["grabbable"] if "grabbable" in t.get("from", []) else []),
            "dev_themes": ["modular", "construction"],
            "map_sequences": [],
            "modular": {"term": tid, "chapter": chapter, "from": t.get("from", []), "expr": t.get("expr", "")},
        }
    return {
        "_doc": "GENERATED by tools/build_modular_registry.py from commons/modular/terms.json — edit the terms, not this file.",
        "artifacts": artifacts,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    doc = build()
    text = json.dumps(doc, indent=1, ensure_ascii=False) + "\n"
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("STALE", OUT)
            return 1
        print("up to date", OUT)
        return 0
    temporary=OUT.with_suffix('.modular.tmp')
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary,OUT)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(doc['artifacts'])} tokens using shared composite / recipe adapters")
    return 0


if __name__ == "__main__":
    sys.exit(main())
