// Exercise the real save store in a disposable repository, never the user's placements.
const fs=require('fs'),path=require('path'),os=require('os'),assert=require('assert');
const root=path.resolve(__dirname,'..'),web=path.resolve(root,'../ada_encyclopedia');
const ts=require(path.join(web,'node_modules/typescript'));
require.extensions['.ts']=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {saveLayout,layoutRevision,LayoutConflict}=require(path.join(web,'src/lib/void-layout-store.ts'));
const {layoutContext}=require(path.join(web,'src/lib/void-layout-context.ts'));
const repo=fs.mkdtempSync(path.join(os.tmpdir(),'ada-void-layout-'));
const dir=path.join(repo,'commons/void'),trial=path.join(dir,'trials/transformation');fs.mkdirSync(trial,{recursive:true});
const original='{"tower":"curated"}\n',first='{"trial":"before"}\n';
fs.writeFileSync(path.join(dir,'rooms.json'),original);fs.writeFileSync(path.join(trial,'rooms.json'),first);
fs.copyFileSync(path.join(root,'commons/void/trials/playable.json'),path.join(dir,'trials/playable.json'));
const desktop=path.join(repo,'Desktop');
const saved=saveLayout(repo,{trial:'after'},layoutRevision(first),desktop,'transformation');
assert.equal(fs.readFileSync(path.join(dir,'rooms.json'),'utf8'),original);
assert.equal(JSON.parse(fs.readFileSync(path.join(trial,'rooms.json'))).trial,'after');
assert.equal(fs.readFileSync(path.join(desktop,'trials/transformation/rooms.json'),'utf8'),fs.readFileSync(path.join(trial,'rooms.json'),'utf8'));
assert(!fs.existsSync(path.join(desktop,'rooms.json')));
assert.equal(fs.readdirSync(path.join(repo,'ada_run/void-editor-backups/transformation')).length,1);
assert.throws(()=>saveLayout(repo,{},layoutRevision(first),desktop,'transformation'),LayoutConflict);
assert.throws(()=>layoutContext(repo,'../../rooms'),/Unknown/);
assert.throws(()=>layoutContext(repo,'noise'),/not been built/);
assert.throws(()=>layoutContext(repo,'__proto__'),/not been built/);
assert.equal(layoutContext(repo).file,path.join(dir,'rooms.json'));
assert.equal(saved.revision,layoutRevision(fs.readFileSync(path.join(trial,'rooms.json'),'utf8')));
saveLayout(repo,{tower:'changed'},layoutRevision(original),desktop);
assert.equal(JSON.parse(fs.readFileSync(path.join(trial,'rooms.json'))).trial,'after');
assert(fs.existsSync(path.join(desktop,'rooms.json')));
console.log(JSON.stringify({checks:13,status:'passed',fixture:repo}));
