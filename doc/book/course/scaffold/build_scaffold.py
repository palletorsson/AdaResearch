#!/usr/bin/env python3
"""build_scaffold.py - the course skeleton, taken from the spine itself.

Palle, 2 October 2026: "we should have used scaffold from the spine sequence".
One chapter per spine sequence, in the spine's order (commons/maps/curriculum_spine.json).
Inside a chapter, one hall per map, in the sequence's order (commons/maps/sequences/<seq>.json).
Inside a hall, the works in Palle's arrangement (the /api/spine-roles data: primary works, his named
boxes, his order, his relation notes). Nothing here is written by a model: it is read from the
spine, so the structure of the course cannot drift from the world it teaches.

Writes scaffold.json and SCAFFOLD.md beside this file. Needs the encyclopedia dev server
(http://localhost:3003) for the arrangement.

    python doc/book/course/scaffold/build_scaffold.py
"""
import json, os, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
API = "http://localhost:3003/api/spine-roles?seq="


def load(path):
    with open(os.path.join(REPO, path), encoding="utf-8") as f:
        return json.load(f)


def arrangement(seq):
    with urllib.request.urlopen(API + seq, timeout=60) as r:
        d = json.load(r)
    for s in d.get("sequences", []):
        if s.get("seq") == seq:
            return s
    return {"maps": []}


def works(layout_list, groups, cards):
    """the layout of one role: cards, Palle's named boxes (with the works in them) and his notes, in his order"""
    out = []
    gname = {g.get("id"): g.get("title") or g.get("id") for g in groups or []}
    for item in layout_list or []:
        kind = item.get("kind")
        if kind == "card":
            out.append({"work": item.get("token")})
        elif kind == "group":
            gid = item.get("id")
            out.append({"box": gname.get(gid, gid), "works": [c["token"] for c in cards or [] if c.get("group") == gid]})
        elif kind == "note":
            out.append({"note": item.get("text", "")})
    return out


spine = load("commons/maps/curriculum_spine.json")["spine"]["sequences"]
chapters = []
for n, entry in enumerate(sorted(spine, key=lambda e: e.get("order", 0)), 1):
    seq = entry["name"]
    seqfile = load("commons/maps/sequences/%s.json" % seq)["sequences"]
    meta = seqfile.get(seq) or next(iter(seqfile.values()))
    arr = arrangement(seq)
    by_map = {m["map"]: m for m in arr.get("maps", [])}
    halls = []
    for m in meta.get("maps", []):
        name = m if isinstance(m, str) else (m.get("name") or m.get("map"))
        a = by_map.get(name, {})
        lay = a.get("layout", {})
        halls.append({
            "hall": name,
            "primary": works(lay.get("primary"), a.get("groups"), a.get("cards")),
            "secondary": works(lay.get("secondary"), a.get("groups"), a.get("cards")),
            "notes": a.get("notes", []),
        })
    chapters.append({
        "chapter": n, "sequence": seq, "title": meta.get("name", seq),
        "truth": meta.get("truth", ""), "demonstration": meta.get("demonstration", ""),
        "halls": halls,
    })

with open(os.path.join(HERE, "scaffold.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump({"source": "curriculum_spine.json + sequences/*.json + /api/spine-roles", "chapters": chapters},
              f, ensure_ascii=False, indent=1)

lines = ["# The course scaffold, read from the spine", "",
         "Generated by `build_scaffold.py`: one chapter per spine sequence, one hall per map, the works in "
         "Palle's arrangement (primary, his named boxes, his order). Rebuild, never edit.", ""]
for c in chapters:
    lines += ["## %d %s (`%s`)" % (c["chapter"], c["title"], c["sequence"]), "",
              "Truth: %s" % c["truth"], "", "Demonstration: %s" % c["demonstration"], ""]
    for h in c["halls"]:
        lines.append("### %s" % h["hall"])
        if not h["primary"]:
            lines.append("- (no primary works in the arrangement yet)")
        for w in h["primary"]:
            if "work" in w:
                lines.append("- %s" % w["work"])
            elif "box" in w:
                lines.append("- **%s**" % w["box"])
                lines += ["  - %s" % t for t in w["works"]]
            else:
                lines.append("- *note:* %s" % w["note"])
        shown = {w["note"] for w in h["primary"] if "note" in w}
        for note in h["notes"]:
            text = note.get("text") if isinstance(note, dict) else note
            if text not in shown:
                lines.append("  > %s" % text)
        lines.append("")
with open(os.path.join(HERE, "SCAFFOLD.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("chapters", len(chapters), "halls", sum(len(c["halls"]) for c in chapters),
      "primary works", sum(len(h["primary"]) for c in chapters for h in c["halls"]))
